"""Cut the self-hosted fonts down to what the site uses.

Every CJK face gets a small core file with exactly the characters that appear in the source (UI copy, song
titles). The two Noto faces also get an extended file with the ~3,700 common characters of GB 2312 level 1,
declared first and with a broad unicode-range, so a browser only fetches it when a page shows a character the
core lacks (an imported song's title, a track name). Latin faces keep Latin-1 plus punctuation.
Output: woff2 in src/assets/fonts and the @font-face sheet in src/styles/fonts.css.
Runs before every build (npm run build); run it by hand with `npm run fonts`.
"""
import pathlib, re
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'fonts-src'
OUT = ROOT / 'src' / 'assets' / 'fonts'
CSS = ROOT / 'src' / 'styles' / 'fonts.css'
OUT.mkdir(parents=True, exist_ok=True)

# every character the site can print from its own source
text = set()
for p in (ROOT / 'src').rglob('*'):
    if p.suffix in ('.ts', '.svelte', '.json', '.css', '.html') and 'assets' not in p.parts:
        s = p.read_text(encoding='utf-8')
        if p.suffix == '.json':  # song files: only the string values matter
            s = ' '.join(re.findall(r'"([^"]*)"', s))
        text.update(s)
text.update('，。、；：？！“”‘’（）《》「」『』—…·～　・♯♭♪↑↓←→×÷±')
core_cjk = sorted({ch for ch in text if ord(ch) >= 0x2E80})

# GB 2312 level 1: the common characters, plus CJK punctuation and full-width forms
common = set()
for hi in range(0xB0, 0xD8):
    for lo in range(0xA1, 0xFF):
        try:
            common.add(bytes([hi, lo]).decode('gb2312'))
        except UnicodeDecodeError:
            pass
common.update(chr(c) for c in range(0x3000, 0x3040))
common.update(chr(c) for c in range(0xFF01, 0xFF5F))

LATIN = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + [0x131, 0x152, 0x153, 0x2BB, 0x2BC, 0x2C6, 0x2DA, 0x2DC] + list(range(0x2000, 0x2070)) + [0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2215, 0x266A, 0x266D, 0x266F, 0xFEFF]


def ranges(cps):
    """compress code points into a unicode-range value"""
    cps = sorted(set(cps))
    out, i = [], 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        out.append(f'U+{cps[i]:X}' if i == j else f'U+{cps[i]:X}-{cps[j]:X}')
        i = j + 1
    return ', '.join(out)


def cut(src, dst, unicodes, axes=None):
    font = TTFont(SRC / src, lazy=False)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    opts.hinting = False
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    if axes and 'fvar' in font:
        font = instancer.instantiateVariableFont(font, axes)
    kept = set(font.getBestCmap().keys())
    font.flavor = 'woff2'
    font.save(OUT / dst)
    return (OUT / dst).stat().st_size, kept


# family, source, weight range, style, stretch, axes, kind
faces = [
    ('Noto Sans SC', 'NotoSansSC[wght].ttf', 'noto-sans-sc', '400 900', 'normal', None, {'wght': (400, 900)}, 'cjk+'),
    ('Noto Serif SC', 'NotoSerifSC[wght].ttf', 'noto-serif-sc', '500 900', 'normal', None, {'wght': (500, 900)}, 'cjk+'),
    ('Shippori Mincho B1', 'ShipporiMinchoB1-ExtraBold.ttf', 'shippori-mincho-b1-800', '800', 'normal', None, None, 'cjk'),
    ('Archivo', 'Archivo-Italic[wdth,wght].ttf', 'archivo-italic', '500 900', 'italic', '100% 125%', {'wght': (500, 900), 'wdth': (100, 125)}, 'latin'),
    ('Cormorant Garamond', 'CormorantGaramond[wght].ttf', 'cormorant-garamond', '500 700', 'normal', None, {'wght': (500, 700)}, 'latin'),
    ('Cormorant Garamond', 'CormorantGaramond-Italic[wght].ttf', 'cormorant-garamond-italic', '500 700', 'italic', None, {'wght': (500, 700)}, 'latin'),
    ('Manufacturing Consent', 'ManufacturingConsent-Regular.ttf', 'manufacturing-consent', '400', 'normal', None, None, 'latin'),
]

css = ['/* generated by scripts/subset-fonts.py; do not edit */']
total = 0


def rule(family, file, weight, style, stretch, urange):
    r = [f'@font-face{{font-family:"{family}"', f'src:url("../assets/fonts/{file}") format("woff2")', f'font-weight:{weight}', f'font-style:{style}', 'font-display:swap']
    if stretch:
        r.append(f'font-stretch:{stretch}')
    if urange:
        r.append(f'unicode-range:{urange}')
    return ';'.join(r) + '}'


for family, src, stem, weight, style, stretch, axes, kind in faces:
    if kind == 'latin':
        size, kept = cut(src, stem + '.woff2', LATIN, axes)
        total += size
        print(f'{stem + ".woff2":40s} {size / 1024:7.1f} KB')
        css.append(rule(family, stem + '.woff2', weight, style, stretch, None))
        continue
    if kind == 'cjk+':
        # declared first: a later face with a matching range wins, so the core below takes precedence
        ext = [ord(c) for c in common]
        size, kept = cut(src, stem + '-common.woff2', ext, axes)
        total += size
        print(f'{stem + "-common.woff2":40s} {size / 1024:7.1f} KB  ({len(kept)} glyphs, fetched only when needed)')
        css.append(rule(family, stem + '-common.woff2', weight, style, stretch, 'U+3000-303F, U+3400-4DBF, U+4E00-9FFF, U+F900-FAFF, U+FF00-FFEF'))
    base = [ord(c) for c in core_cjk] + (LATIN if kind == 'cjk+' else list(range(0x20, 0x7F)) + [0xFA, 0xDA])
    size, kept = cut(src, stem + '.woff2', base, axes)
    total += size
    print(f'{stem + ".woff2":40s} {size / 1024:7.1f} KB  ({len(kept)} glyphs)')
    css.append(rule(family, stem + '.woff2', weight, style, stretch, ranges(kept)))

CSS.write_text('\n'.join(css) + '\n', encoding='utf-8')
print(f'{len(core_cjk)} CJK characters in the core, {len(common)} in the common set; {total / 1024:.0f} KB in all')
